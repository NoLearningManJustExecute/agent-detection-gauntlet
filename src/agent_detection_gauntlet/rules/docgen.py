"""Render docs/detections.md from the rule files. The rules are the source of truth."""

from __future__ import annotations

from pathlib import Path

from agent_detection_gauntlet.rules.loader import load_rule_file, rule_files
from agent_detection_gauntlet.rules.model import (
    BaselineLogic,
    MatchLogic,
    Rule,
    SequenceLogic,
)
from agent_detection_gauntlet.schema.common import TIER_ORDER

_HEADER = """# Detections

Generated by `gauntlet rules-doc` from `rules/`. Do not edit by hand; CI fails when this file and
the rules disagree. Rules are hypotheses until scored: this catalog carries no results. OWASP LLM
IDs use the 2025 edition's numbers; see [mappings.md](mappings.md).

"""


def _logic_kind(rule: Rule) -> str:
    logic = rule.logic
    if isinstance(logic, MatchLogic):
        return "match"
    if isinstance(logic, SequenceLogic):
        return "sequence: " + ", then ".join(step.name for step in logic.sequence.steps)
    if isinstance(logic, BaselineLogic):
        return f"baseline: {logic.baseline.statistic.value}"
    return "threshold"


def _fitted_lines(rule: Rule) -> list[str]:
    if not isinstance(rule.logic, BaselineLogic) or rule.fitted is None:
        return []
    spec, fitted = rule.logic.baseline, rule.fitted
    if fitted.threshold is not None:
        value = f"percentile {spec.percentile} of matching events per trace = {fitted.threshold}"
    else:
        counts = fitted.transitions or {}
        value = (
            f"{len(counts)} transitions, {sum(counts.values())} observed; "
            f"rare below rate {spec.max_rate}"
        )
    return [
        f"- **Fitted:** {value}, on {fitted.traces} {fitted.population} traces.",
        f"- **Fit command:** `{fitted.command}`",
    ]


def _mapping_cell(ids: list[str]) -> str:
    return ", ".join(ids) if ids else "none"


def _rule_section(rule: Rule) -> str:
    mappings = rule.mappings
    lines = [
        f"### {rule.id}: {rule.title}",
        "",
        f"- **Version:** {rule.version} ({rule.status.value}), **severity:** {rule.severity.value}",
        f"- **Logic:** {_logic_kind(rule)}",
        f"- **Telemetry:** {', '.join(kind.value for kind in rule.telemetry)}",
        f"- **Mappings:** ATLAS {_mapping_cell(mappings.atlas)}; "
        f"OWASP LLM {_mapping_cell(mappings.owasp_llm)}; "
        f"OWASP Agentic {_mapping_cell(mappings.owasp_agentic)}; "
        f"ATT&CK {_mapping_cell(mappings.attack)}",
        f"- **Fixtures:** {len(rule.fixtures.tp)} tp, {len(rule.fixtures.fp)} fp",
        *_fitted_lines(rule),
        "",
        rule.description,
        "",
        f"**Hypothesis.** {rule.hypothesis}",
        "",
        "**Limitations.**",
        "",
        *(f"- {item}" for item in rule.limitations),
        "",
    ]
    return "\n".join(lines)


def render(rules_dir: Path) -> str:
    rules = [load_rule_file(path) for path in rule_files(rules_dir)]
    out = [_HEADER, "| Rule | Tier | Severity | Title |\n|---|---|---|---|\n"]
    for tier in TIER_ORDER:
        for rule in (r for r in rules if r.tier is tier):
            out.append(f"| {rule.id} | {tier.value} | {rule.severity.value} | {rule.title} |\n")
    out.append("\n")
    for tier in TIER_ORDER:
        out.append(f"## {tier.value.capitalize()} tier\n\n")
        out.extend(_rule_section(rule) + "\n" for rule in rules if rule.tier is tier)
    return "".join(out).rstrip("\n") + "\n"
